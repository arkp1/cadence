import { chromium } from 'playwright';
const b = await chromium.launch();
let errs = [];
const p = await b.newPage({ viewport: { width: 1280, height: 860 }, timezoneId: 'Asia/Kolkata' });
p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:3000/form/get-started', { waitUntil: 'networkidle' });
await p.screenshot({ path: '/home/user/shots/form-1.png' });
const html = await p.$$eval('.routing-form .field', fs => fs.map(f => f.querySelector('.field-label')?.textContent + ' :: ' + [...f.querySelectorAll('input,select,textarea')].map(i=>i.tagName+':'+(i.type||'')).join(',') + ' :: ' + [...f.querySelectorAll('option,label.opt')].map(o=>o.textContent).join('|')));
console.log(html.join('\n'));
await p.goto('http://localhost:3000/poll/team-offsite', { waitUntil: 'networkidle' });
await p.click('.poll-option >> nth=0'); await p.click('.poll-option >> nth=2');
await p.fill('.poll-form input >> nth=0', 'Grace Hopper'); await p.fill('.poll-form input[type=email]', 'grace@example.com');
await p.click('.poll-form button'); await p.waitForTimeout(800);
await p.screenshot({ path: '/home/user/shots/poll-1.png' });
await p.goto('http://localhost:3000/alex', { waitUntil: 'networkidle' }); await p.screenshot({ path: '/home/user/shots/profile-1.png' });
const m = await b.newPage({ viewport: { width: 390, height: 844 }, timezoneId: 'America/New_York' });
m.on('pageerror', e => errs.push(e.message));
await m.goto('http://localhost:3000/alex/sales-demo', { waitUntil: 'networkidle' }); await m.waitForTimeout(500);
await m.screenshot({ path: '/home/user/shots/mobile-1.png', fullPage: true });
console.log('errors', JSON.stringify(errs));
await b.close();
